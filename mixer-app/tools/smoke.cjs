const { app } = require('electron');
const fs = require('node:fs/promises');
const path = require('node:path');
process.argv.push('--no-auto-connect');
app.setPath('userData', path.join(__dirname, '../.qa-profile-v3'));
app.on('browser-window-created', (_, win) => {
  win.webContents.setBackgroundThrottling(false);
  win.showInactive();
  win.webContents.on('console-message', (_, level, message) => { if (level >= 2) console.error(message); });
  win.webContents.once('did-finish-load', async () => {
    try {
      const result = await win.webContents.executeJavaScript(`(async () => {
        const pause = ms => new Promise(r => setTimeout(r, ms));
        await pause(1800);
        if(document.querySelectorAll('.channel').length !== 4) throw Error('Expected 4 channels');
        if(document.querySelectorAll('.layout-option').length !== 3) throw Error('Expected 3 layouts');
        if(document.documentElement.lang!=='pt-BR'||$('connection').textContent.trim()!=='Desconectado')throw Error('Portuguese locale not applied');
        if(document.querySelector('header .brand').tagName!=='IMG')throw Error('Old brand mark remains');
        updateStatus({connected:false,message:'Aguardando firmware MX Nano v2…'});
        if($('connection').textContent.trim()!=='Conectando…'||!$('deviceError').textContent.includes('Aguardando'))throw Error('Connection progress is hidden');
        updateStatus({connected:false,message:'Falha de teste serial'});
        if($('deviceError').textContent!=='Falha de teste serial')throw Error('Connection error is hidden');
        updateStatus({connected:true,message:'Nano conectado · Serial',device:{firmware:'MX Nano v2.0',oledAddress:null}});
        if($('deviceFirmware').textContent!=='MX Nano v2.0'||!$('deviceError').textContent.includes('OLED ausente'))throw Error('USB-only status is hidden');
        updateStatus((await window.mixer.state()).status);
        if($('about').textContent.includes('Independent custom build')||$('about').querySelector('.note'))throw Error('Removed About text remains');
        if(!layoutNames.includes('Colunas')||!layoutNames.includes('Linhas'))throw Error('Layout names not translated');
        const sources = await window.mixer.sessions();
        const audioDevices = await window.mixer.endpoints();
        const all = await window.mixer.allApps();
        const hardware = await window.mixer.devices();
        if(document.querySelector('#discord')||document.querySelector('#documentation')||document.querySelector('#globalMidi')||document.querySelector('#channelMidiTab'))throw Error('Removed controls remain');
        if(window.mixer.midiPorts||window.mixer.help)throw Error('Removed API remains');
        if('midi' in config||config.channels.some(c=>'midi' in c))throw Error('Legacy MIDI configuration remains active');
        config.channels.forEach((c,i)=>{c.targets=[];c.symbol=null;c.volume=i;c.icon=null;c.bitmap=Array(32).fill(0);updateChannel(i);});
        config.layout=0;await window.mixer.save(config);refreshPreviews();
        const baseline=structuredClone(config);
        openChannel(0); await refreshApps();
        if($('channelTitle').textContent!=='Configurar canal 1')throw Error('Channel title not translated');
        const first=document.querySelector('#apps input');
        if(first){first.click();await pause(700);const c=(await window.mixer.state()).config.channels[0];if(!c.targets.length)throw Error('Application checkbox did not persist');if(c.symbol||c.icon||c.bitmap.some(Boolean))throw Error('Application auto-selected an icon');}
        setChannelTab('utilities');
        if(document.querySelectorAll('#systemApps .group-title').length!==3)throw Error('System groups missing');
        setChannelTab('labels');
        if(document.querySelector('#textOptions')||document.querySelector('#imageOptions')||document.querySelector('#uploadIcon'))throw Error('Removed label options remain');
        $('iconSearch').value='discord';renderIconGrid();
        const iconButton=document.querySelector('#iconGrid button[data-icon="brand-discord"]');
        if(!iconButton)throw Error('Discord missing');iconButton.click();await pause(600);
        const saved=(await window.mixer.state()).config.channels[0];
        if(saved.symbol!=='brand-discord'||!saved.bitmap.some(Boolean))throw Error('Discord/OLED bitmap did not persist');
        if(document.querySelector('#channels .assign img')?.src!==saved.icon)throw Error('Slider icon mismatch');
        const bitmap=await toBitmap(saved.icon);if(JSON.stringify(bitmap)!==JSON.stringify(saved.bitmap))throw Error('OLED mismatch');
        $('iconSearch').value='volume';renderIconGrid();if(!document.querySelector('[data-icon="volume-high"]'))throw Error('Volume missing');
        $('iconSearch').value='fone';renderIconGrid();if(!document.querySelector('[data-icon="headphones"]'))throw Error('Portuguese search failed');
        $('iconSearch').value='';iconCategory='all';renderIconGrid();while(iconLimit<iconResults.length)appendIconPage();if(document.querySelectorAll('#iconGrid button').length!==icons.length)throw Error('Catalog truncation');
        $('removeIcon').click();await pause(300);const cleared=(await window.mixer.state()).config.channels[0];if(cleared.symbol||cleared.icon||cleared.bitmap.some(Boolean))throw Error('Clear did not persist');
        await chooseIcon('volume-high');const restored=(await window.mixer.state()).config;config=structuredClone(restored);config.channels.forEach((_,i)=>updateChannel(i));if(!assigns[0].querySelector('img'))throw Error('Saved selection not restored');
        document.querySelectorAll('.layout-option')[1].click();await pause(200);if((await window.mixer.state()).config.layout!==1)throw Error('Layout persistence failed');
        $('channelDialog').close();config=baseline;await window.mixer.save(config);config.channels.forEach((_,i)=>updateChannel(i));refreshPreviews();
        return {channels:4,layouts:3,icons:icons.length,brands:icons.filter(i=>i.category==='apps').length,iconSync:true,noAutomaticIcons:true,removedControlsAbsent:true,noMidiConfiguration:true,portugueseSearch:true,fullCatalog:true,allApps:all.length,audioDevices:audioDevices.length,sessions:sources.length,compatibleDevices:hardware.length};
      })()`);
      const painted = () => win.webContents.executeJavaScript('new Promise(r=>requestAnimationFrame(()=>requestAnimationFrame(r)))');
      await painted();
      await fs.writeFile(path.join(__dirname, '../../mixer-preview.png'), (await win.webContents.capturePage()).toPNG());
      await win.webContents.executeJavaScript(`openChannel(0);void refreshApps()`);
      await new Promise(r=>setTimeout(r,500));
      await painted();
      await fs.writeFile(path.join(__dirname, '../../mixer-programs-preview.png'),(await win.webContents.capturePage()).toPNG());
      await win.webContents.executeJavaScript(`setChannelTab('labels')`);
      await painted();
      await fs.writeFile(path.join(__dirname, '../../mixer-labels-preview.png'),(await win.webContents.capturePage()).toPNG());
      await win.webContents.executeJavaScript(`$('channelDialog').close();void openSettings()`);
      await new Promise(r=>setTimeout(r,400));
      await painted();
      await fs.writeFile(path.join(__dirname, '../../mixer-settings-preview.png'),(await win.webContents.capturePage()).toPNG());
      await win.webContents.executeJavaScript(`setSettingsTab('about')`);
      await painted();
      await new Promise(r=>setTimeout(r,250));
      await fs.writeFile(path.join(__dirname, '../../mixer-about-preview.png'),(await win.webContents.capturePage()).toPNG());
      await win.webContents.executeJavaScript(`$('deviceDialog').close()`);
      await painted();
      await new Promise(r=>setTimeout(r,350));
      await fs.writeFile(path.join(__dirname, '../../mixer-preview.png'),(await win.webContents.capturePage()).toPNG());
      console.log(JSON.stringify(result));app.quit();
    } catch(error){console.error(error);app.exit(1);}
  });
});
setTimeout(()=>{console.error('Smoke timeout');app.exit(1);},65000).unref();
require('../main.cjs');
